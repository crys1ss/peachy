"""Unit tests for double-tap C detection logic and low-level hook guards."""

from __future__ import annotations

from unittest.mock import MagicMock, patch

import pytest

from core import win32
from core.double_tap import DoubleTapDetector, DoubleTapHook


def test_fast_c_c_fires():
    """Verify 'c c' pressed quickly within the 280ms interval fires double-tap."""
    detector = DoubleTapDetector(interval_ms=280)

    # First 'C' press and release at t=1.000s
    assert detector.process_key(win32.VK_C, is_down=True, timestamp=1.000) is False
    assert detector.process_key(win32.VK_C, is_down=False, timestamp=1.050) is False

    # Second 'C' press at t=1.200s (200ms elapsed <= 280ms)
    assert detector.process_key(win32.VK_C, is_down=True, timestamp=1.200) is True


def test_slow_c_c_does_not_fire():
    """Verify 'c c' pressed slowly (> 280ms) does NOT fire double-tap."""
    detector = DoubleTapDetector(interval_ms=280)

    # First 'C' press and release at t=1.000s
    assert detector.process_key(win32.VK_C, is_down=True, timestamp=1.000) is False
    assert detector.process_key(win32.VK_C, is_down=False, timestamp=1.050) is False

    # Second 'C' press at t=1.350s (350ms elapsed > 280ms)
    assert detector.process_key(win32.VK_C, is_down=True, timestamp=1.350) is False

    # A third 'C' quickly after the second (1.450s, 100ms later) should now fire!
    assert detector.process_key(win32.VK_C, is_down=False, timestamp=1.400) is False
    assert detector.process_key(win32.VK_C, is_down=True, timestamp=1.450) is True


def test_c_x_c_does_not_fire():
    """Verify an intermediate key between C presses resets the sequence."""
    detector = DoubleTapDetector(interval_ms=280)

    # First 'C'
    assert detector.process_key(win32.VK_C, is_down=True, timestamp=1.000) is False
    assert detector.process_key(win32.VK_C, is_down=False, timestamp=1.050) is False

    # Intervening 'X' key press (0x58)
    assert detector.process_key(0x58, is_down=True, timestamp=1.100) is False
    assert detector.process_key(0x58, is_down=False, timestamp=1.120) is False

    # Second 'C' within 280ms from first 'C', but interrupted by 'X'
    assert detector.process_key(win32.VK_C, is_down=True, timestamp=1.150) is False


def test_ctrl_c_ctrl_c_does_not_fire():
    """Verify modifier chords (Ctrl+C) never trigger double-tap."""
    detector = DoubleTapDetector(interval_ms=280)

    # Ctrl+C first tap
    assert detector.process_key(win32.VK_C, is_down=True, ctrl_down=True, timestamp=1.000) is False
    assert detector.process_key(win32.VK_C, is_down=False, ctrl_down=True, timestamp=1.050) is False

    # Ctrl+C second tap
    assert detector.process_key(win32.VK_C, is_down=True, ctrl_down=True, timestamp=1.150) is False


def test_alt_and_win_modifiers_do_not_fire():
    """Verify Alt+C and Win+C do not trigger double-tap."""
    detector = DoubleTapDetector(interval_ms=280)

    # Alt+C
    assert detector.process_key(win32.VK_C, is_down=True, alt_down=True, timestamp=1.000) is False
    assert detector.process_key(win32.VK_C, is_down=True, alt_down=True, timestamp=1.100) is False

    # Win+C
    assert detector.process_key(win32.VK_C, is_down=True, win_down=True, timestamp=2.000) is False
    assert detector.process_key(win32.VK_C, is_down=True, win_down=True, timestamp=2.100) is False


def test_held_c_auto_repeat_does_not_fire():
    """Verify holding the 'C' key down (OS auto-repeat without release) does NOT fire."""
    detector = DoubleTapDetector(interval_ms=280)

    # Physical down
    assert detector.process_key(win32.VK_C, is_down=True, timestamp=1.000) is False

    # Repeated down events generated by OS keyboard repeat without an intervening keyup
    assert detector.process_key(win32.VK_C, is_down=True, timestamp=1.050) is False
    assert detector.process_key(win32.VK_C, is_down=True, timestamp=1.100) is False
    assert detector.process_key(win32.VK_C, is_down=True, timestamp=1.150) is False
    assert detector.process_key(win32.VK_C, is_down=True, timestamp=1.200) is False


def test_injected_events_ignored():
    """Verify synthetic / injected events (LLKHF_INJECTED) are ignored."""
    detector = DoubleTapDetector(interval_ms=280)

    # First injected C
    assert detector.process_key(win32.VK_C, is_down=True, is_injected=True, timestamp=1.000) is False
    # Second injected C
    assert detector.process_key(win32.VK_C, is_down=True, is_injected=True, timestamp=1.100) is False


def test_double_tap_hook_lifecycle(qtbot):
    """Verify DoubleTapHook installs, pauses, unpauses, and uninstalls cleanly."""
    with patch("core.win32.set_windows_hook", return_value=12345) as mock_set, \
         patch("core.win32.unhook_windows_hook", return_value=True) as mock_unhook:

        hook = DoubleTapHook(interval_ms=300)

        # 1. Enable hook -> installs
        hook.set_enabled(True)
        assert hook.is_installed() is True
        mock_set.assert_called_once()

        # 2. Pause hook -> uninstalls from hook chain
        hook.set_paused(True)
        assert hook.is_installed() is False
        mock_unhook.assert_called_once()

        # 3. Unpause hook -> reinstalls
        hook.set_paused(False)
        assert hook.is_installed() is True

        # 4. Disable hook -> uninstalls
        hook.set_enabled(False)
        assert hook.is_installed() is False
